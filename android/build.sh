#!/bin/bash
# Builds Focus Guard APK without Gradle: javac -> d8 -> aapt2 -> zipalign -> apksigner.
set -euo pipefail
cd "$(dirname "$0")"

SDK=~/Library/Android/sdk
BT=$SDK/build-tools/35.0.0
JAR=$SDK/platforms/android-36/android.jar
OUT=build
rm -rf $OUT && mkdir -p $OUT/classes $OUT/res

# FG_PLAY=1: Google Play build. Play forbids using accessibility to stop users from turning an app
# off, so that build has no settings guard (Flavor.PLAY). Sideload/GitHub builds keep it.
PLAY=false; [ "${FG_PLAY:-}" = 1 ] && PLAY=true
MANIFEST=app/AndroidManifest.xml
if $PLAY; then
    # No device admin receiver and no REQUEST_IGNORE_BATTERY_OPTIMIZATIONS (Play restricted use).
    MANIFEST=$OUT/AndroidManifest.xml
    python3 - app/AndroidManifest.xml $MANIFEST <<'PY'
import re, sys
s = open(sys.argv[1]).read()
s = re.sub(r'\n *<uses-permission android:name="android.permission.REQUEST_IGNORE_BATTERY_OPTIMIZATIONS" />', '', s)
s, n = re.subn(r'\n *<receiver\s+android:name="\.Admin".*?</receiver>', '', s, flags=re.S)
assert n == 1 and 'BATTERY' not in s, 'manifest filter failed'
open(sys.argv[2], 'w').write(s)
PY
fi

$BT/aapt2 compile --dir app/res -o $OUT/res.zip
# Assets: app/assets plus the adult domain list (URL check on phones without root).
cp -R app/assets $OUT/assets && cp magisk/adult_hosts $OUT/assets/
# The owner's personal keywords never ship in a Play build.
$PLAY && rm -f $OUT/assets/keywords.local.json
# R.java (widget layout ids) goes to $OUT/gen with Flavor.java.
mkdir -p $OUT/gen
$BT/aapt2 link -o $OUT/base.apk -I $JAR --manifest $MANIFEST \
    -A $OUT/assets --java $OUT/gen $OUT/res.zip

GEN=$OUT/gen/com/alrasin/focusguard && mkdir -p $GEN
printf 'package com.alrasin.focusguard;\n\n/** Generated by build.sh. */\nfinal class Flavor {\n    static final boolean PLAY = %s;\n}\n' $PLAY > $GEN/Flavor.java
javac --release 11 -nowarn -cp $JAR -d $OUT/classes $(find app/src $OUT/gen -name '*.java')
$BT/d8 --min-api 26 --lib $JAR --output $OUT $(find $OUT/classes -name '*.class')
(cd $OUT && zip -q base.apk classes.dex)

$BT/zipalign -f 4 $OUT/base.apk $OUT/aligned.apk
# Signing: release builds set FG_KEYSTORE + FG_KS_PASS (env). Otherwise a local key is made once.
# Keep using the same key: Android refuses an update signed with a different one.
KS=${FG_KEYSTORE:-focusguard.keystore}
export KSPASS=${FG_KS_PASS:-focusguard}
if [ ! -f "$KS" ]; then
    [ -n "${FG_KEYSTORE:-}" ] && { echo "Keystore $KS not found" >&2; exit 1; }
    keytool -genkeypair -keystore "$KS" -alias fg -keyalg RSA -keysize 2048 -validity 10000 \
        -storepass "$KSPASS" -keypass "$KSPASS" -dname "CN=Focus Guard" >/dev/null 2>&1
fi
KSALIAS=${FG_KS_ALIAS:-fg}

if $PLAY; then
    # Play wants an AAB: proto-format resources -> base module zip -> bundletool -> jarsigner.
    # bundletool: https://github.com/google/bundletool/releases (jar kept outside the repo).
    BUNDLETOOL=${BUNDLETOOL:-~/.cache/bundletool/bundletool.jar}
    [ -f "$BUNDLETOOL" ] || { echo "bundletool jar not found: $BUNDLETOOL" >&2; exit 1; }
    $BT/aapt2 link --proto-format -o $OUT/proto.apk -I $JAR --manifest $MANIFEST \
        -A $OUT/assets $OUT/res.zip
    B=$OUT/bundle && mkdir -p $B/manifest $B/dex
    (cd $B && unzip -q ../proto.apk)
    mv $B/AndroidManifest.xml $B/manifest/ && cp $OUT/classes.dex $B/dex/
    (cd $B && zip -qr ../base.zip .)
    rm -f FocusGuard-play.aab
    java -jar "$BUNDLETOOL" build-bundle --modules=$OUT/base.zip --output=FocusGuard-play.aab
    jarsigner -keystore "$KS" -storepass:env KSPASS -keypass:env KSPASS -sigalg SHA256withRSA \
        -digestalg SHA-256 FocusGuard-play.aab "$KSALIAS" >/dev/null
    echo "Built $(pwd)/FocusGuard-play.aab"
    # Same build as an APK, for testing on a phone/emulator before uploading.
    $BT/apksigner sign --ks "$KS" --ks-key-alias "$KSALIAS" --ks-pass env:KSPASS \
        --out FocusGuard-play.apk $OUT/aligned.apk
    echo "Built $(pwd)/FocusGuard-play.apk (no Magisk module for Play builds)"
    exit 0
fi

$BT/apksigner sign --ks "$KS" --ks-key-alias "$KSALIAS" --ks-pass env:KSPASS \
    --out FocusGuard.apk $OUT/aligned.apk
echo "Built $(pwd)/FocusGuard.apk"

# Flashable Magisk module: watchdog + bundled APK, versions taken from the manifest.
CODE=$(sed -n 's/.*android:versionCode="\([0-9]*\)".*/\1/p' app/AndroidManifest.xml)
NAME=$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' app/AndroidManifest.xml)
MOD=$OUT/module
mkdir -p $MOD/META-INF/com/google/android
cp magisk/{customize.sh,service.sh,action.sh,uninstall.sh,guard.sh,remove.sh,adult_hosts,private_dns} FocusGuard.apk $MOD/
sed "s/^version=.*/version=$NAME/; s/^versionCode=.*/versionCode=$CODE/" magisk/module.prop > $MOD/module.prop
echo "$CODE" > $MOD/apk_version
# Standard Magisk installer stub.
printf '#!/sbin/sh\n#################\n# Initialization\n#################\numask 022\nui_print() { echo "$1"; }\nOUTFD=$2\nZIPFILE=$3\n. /data/adb/magisk/util_functions.sh\ninstall_module\nexit 0\n' \
    > $MOD/META-INF/com/google/android/update-binary
echo "#MAGISK" > $MOD/META-INF/com/google/android/updater-script
rm -f FocusGuard-module.zip && (cd $MOD && zip -qr ../../FocusGuard-module.zip .)
echo "Built $(pwd)/FocusGuard-module.zip"
